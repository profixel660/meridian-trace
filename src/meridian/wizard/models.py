class ImportJobResponse(BaseModel):
    job_id: str = Field(
        description=(
            "Opaque job ID. Poll ``GET /setup/import/{job_id}`` until "
            "``status='succeeded' | 'failed'``."
        )
    )


class ImportErrorEntry(BaseModel):
    """One per-file failure inside an import job.

    Replaces the alpha-10-and-earlier ``errors: list[str]`` of opaque
    "{filename}: {message}" strings. The frontend uses ``code`` to route
    rendering (which icon, which remediation copy) and ``file`` /
    ``message`` for the audit list.
    """

    code: ImportErrorCode = Field(
        description=(
            "Stable machine-readable code. New values are added in scoped "
            "releases; removing one is a frontend-breaking change."
        ),
    )
    file: str = Field(
        description="Basename of the failing file (no absolute path leaked to UI).",
    )
    message: str = Field(
        description=(
            "Underlying error message verbatim. Safe to render: the import "
            "worker only constructs these from caught exceptions whose "
            "messages are themselves user-facing."
        ),
    )


class ImportErrorGroup(BaseModel):
    """Same-code errors coalesced into one row.

    Alpha-11 finding: 18 identical 800-byte strings for "ODA File Converter
    not installed" wasted bytes and was unreadable. Coalesced groups
    surface "18 .dwg files were skipped — install ODA File Converter to
    enable DWG ingest" as one row with an expandable file list.
    """

    code: ImportErrorCode = Field(
        description="The shared error code for every entry in this group.",
    )
    count: int = Field(
        ge=1,
        description="Number of files in the group.",
    )
    summary: str = Field(
        description=(
            "PM-language one-liner ('18 AutoCAD drawings were skipped'). "
            "Generated server-side so frontend rendering is one consistent "
            "string regardless of which client is reading."
        ),
    )
    remediation: str = Field(
        description=(
            "Specific user action that resolves this category. PM-language. "
            "Empty string (NOT null) when no remediation applies (e.g. "
            "code='unknown')."
        ),
    )
    files: list[str] = Field(
        default_factory=list,
        description=(
            "Basenames of every file in this group. The GUI renders this as "
            "an expandable list; capped at 100 server-side to keep the "
            "response payload bounded."
        ),
    )
    truncated: bool = Field(
        default=False,
        description=(
            "True when the file list was truncated to the 100-entry cap. "
            "GUI surfaces 'and N more' when set."
        ),
    )


class ImportJobStatusResponse(BaseModel):
    """Mirrors the shape of ``GET /projects/{name}/jobs/{job_id}`` enough that
    the GUI can reuse the same poll loop component."""

    job_id: str = Field(description="The job ID echoed back.")
    status: Literal["pending", "running", "succeeded", "failed"] = Field(
        description="Three-plus-one-outcome state machine.",
    )
    total: int = Field(description="Number of files queued.")
    completed: int = Field(description="Number of files finished (success + dedup + error).")
    imported: int = Field(description="Number of files genuinely imported (excludes dedup).")
    deduped: int = Field(description="Number of files skipped because content_hash already present.")
    errors: list[str] = Field(
        default_factory=list,
        description=(
            "DEPRECATED in alpha-11: kept populated for one release so a "
            "pinned alpha-10-or-earlier frontend bundle keeps rendering. "
            "Use ``error_groups`` instead. Will be removed in alpha-13."
        ),
    )
    error_groups: list[ImportErrorGroup] = Field(
        default_factory=list,
        description=(
            "Coalesced view of ``errors`` — same data, grouped by error "
            "code with PM-language summary and remediation."
        ),
    )


class ImportSkipRequest(BaseModel):
    project_slug: str = Field(
        description="Slug of the project the user is skipping document import for.",
        min_length=1,
    )


class ImportSkipResponse(BaseModel):
    acknowledged: Literal[True] = Field(
        description="Always true on success — the call is idempotent.",
    )


