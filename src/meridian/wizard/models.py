"""Pydantic request/response models for the GUI setup wizard.

Every model carries ``Field(description=...)`` so the OpenAPI document
generated by FastAPI is self-describing for the Tauri-bundled SPA's typed
client (``apps/web/src/lib/setupClient.ts``). Three-outcome enum fields
(``outcome``, ``next_step``) use ``Literal`` for type-stable codegen.

Alpha-11 contract additions
---------------------------

The folder-import response gained two structured fields after a real-world
SME import surfaced 18 identical "ODA File Converter not installed"
strings inside ``failed: list[str]``:

* :class:`ImportErrorGroup` — same-cause errors coalesced into one entry
  with a ``code``, a remediation hint, and the affected filenames. The
  GUI renders one row per group instead of one per file, and surfaces a
  single actionable fix per category.

* :class:`OdaStatus` — pre-flight detection of the ODA File Converter
  binary (required for ``.dwg`` ingest). Surfaced on the scan response
  so the GUI can warn BEFORE the user kicks off an import that 5% of
  their corpus will be skipped — and on the post-import status response
  so the partial-success panel can offer "install ODA and re-scan" as a
  remediation.

The legacy ``failed: list[str]`` / ``errors: list[str]`` fields stay
populated alongside ``failed_groups`` / ``error_groups`` so an older
pinned frontend bundle running against an alpha-11 backend keeps
working. We will drop the flat lists in alpha-13 once the gauntlet
records 2 releases of green frontend pivots.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field

# Stable machine-readable error codes the frontend uses to pick remediation
# copy / route the partial-success panel. Adding a new code is a
# scoped-tier change; removing one is systemic (frontend has hardcoded
# branches keyed off these strings).
ImportErrorCode = Literal[
    "oda_missing",         # ODA File Converter not installed (DWG ingest)
    "pdf_unreadable",      # pypdf / pdfplumber rejected the file
    "file_locked",         # Windows sharing violation
    "permission_denied",   # Errno 13 / read-only filesystem
    "file_missing",        # path.exists() returned False at import time
    "unsupported_mime",    # dispatcher refused (NotImplementedError)
    "worker_aborted",      # BaseException escaped per-file try/except
    "unknown",             # fall-through; frontend renders raw message
]

# --------------------------------------------------------------------------
# Shared enums
# --------------------------------------------------------------------------

# What the wizard should render next. ``ready`` is the "all required steps
# done — show the Finish button" state; ``complete`` is post-finish.
NextStep = Literal["api_key", "first_project", "first_documents", "ready", "complete"]

# Three-outcome key-validation result. ``unable_to_verify`` covers the
# offline / SDK-import / transient-network case so a flaky network doesn't
# punish the user (mirrors meridian.onboarding.wizard._validate_anthropic_key).
ApiKeyOutcome = Literal["valid", "invalid", "unable_to_verify"]


# --------------------------------------------------------------------------
# /setup/state
# --------------------------------------------------------------------------


class SetupStateResponse(BaseModel):
    """Aggregated wizard progress — driven by the persisted state file."""

    complete: bool = Field(
        description=(
            "True iff the three required steps (api_key, first_project, and "
            "first_documents OR documents_skipped) are all done. Idempotent — "
            "a re-poll never flips back to False."
        )
    )
    api_key_set: bool = Field(
        description=(
            "True if the API key has been validated (or accepted as "
            "'unable_to_verify' for offline installs) and persisted to the OS "
            "keychain."
        )
    )
    first_project_slug: str | None = Field(
        default=None,
        description="Slug of the project the wizard created, or null if not yet created.",
    )
    first_project_name: str | None = Field(
        default=None,
        description="Human-readable name of the wizard-created project, or null.",
    )
    first_project_dir: str | None = Field(
        default=None,
        description=(
            "Absolute path of the projects directory the wizard wrote into "
            "(may differ from settings.projects_dir if the user picked a "
            "custom location). Null until first_project step completes."
        ),
    )
    documents_imported: int = Field(
        default=0,
        description="How many documents the wizard imported (0 if skipped).",
    )
    documents_skipped: bool = Field(
        default=False,
        description="True if the user explicitly skipped the document-import step.",
    )
    next_step: NextStep = Field(
        description=(
            "Which step the GUI should render. 'ready' = all required steps "
            "done but /setup/complete not yet called; 'complete' = wizard "
            "fully finished."
        )
    )


