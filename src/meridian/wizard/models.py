# Round-18: PMs don't think in files; they think in project folders. The
# scan endpoint produces a manifest the GUI renders as "we found X PDFs,
# Y DOCXs, Z DWGs in this folder; ingest all of them?"; the import
# endpoint kicks off the actual ingest job. Both are reusable beyond the
# wizard (e.g. CLI ``meridian projects scan-folder``).


class FolderScanRequest(BaseModel):
    folder_path: str = Field(
        description=(
            "Absolute path of the folder to scan. The server walks it "
            "recursively, classifies files by extension, and returns a "
            "manifest. No DB writes."
        ),
        min_length=1,
    )


class FolderSkipEntry(BaseModel):
    path: str = Field(description="Absolute path of the skipped file.")
    reason: Literal[
        "unsupported_extension",
        "access_denied",
        "hidden_or_system",
    ] = Field(
        description=(
            "Why the file was skipped. Stable enum so the GUI can render "
            "filter chips ('show 12 unsupported files', etc.) and group "
            "the audit list."
        )
    )


class OdaStatus(BaseModel):
    """ODA File Converter availability — pre-flight detection for DWG ingest.

    Alpha-11 finding: an SME's first import silently failed on every
    ``.dwg`` because ODA isn't bundled with the installer. This response
    field lets the GUI warn upfront ("18 of your 347 files are AutoCAD
    drawings; install ODA File Converter to ingest them") instead of
    burying the same error 18 times in a post-import ``failed[]`` list.

    Fields:

    * ``available`` — True iff ``meridian.ingest.dwg.oda_available()``
      located the binary via the env var, PATH, or default Windows
      install glob.
    * ``version`` — best-effort parsed version string. None when
      unavailable OR when the binary refuses ``--version`` (older
      releases). Don't render as a gate — render as a footnote.
    * ``install_url`` — the canonical URL for the installer download.
      Constant per release; surfaced in this field so the frontend
      doesn't hardcode it (one place to change if ODA's hosting moves).
    * ``binary_path`` — absolute path of the located binary, or null
      when unavailable. Surfaced for ops/debug; the GUI shows it as
      a small "found at: ..." line under the green tick.
    """

    available: bool = Field(
        description="True iff ODA File Converter was located.",
    )
    version: str | None = Field(
        default=None,
        description="Best-effort version string ('25.4.0'). May be null.",
    )
    install_url: str = Field(
        description=(
            "Canonical installer URL surfaced in remediation copy. "
            "Frontend should not hardcode this."
        ),
    )
    binary_path: str | None = Field(
        default=None,
        description="Absolute path of the located binary, or null when unavailable.",
    )


class FolderScanResponse(BaseModel):
    folder_path: str = Field(description="Resolved (absolute) folder path the scan ran against.")
    folder_name: str = Field(
        description=(
            "The folder's basename (e.g. ``Shell-C-D``). Used by the GUI as "
            "the default project-name suggestion before slugification."
        )
    )
    files_by_kind: dict[str, list[str]] = Field(
        description=(
            "Bucketed file paths by kind (``pdf``, ``docx``, ``xlsx``, "
            "``dwg``, ``eml``, ``msg``). Every supported kind is always "
            "present as a key — empty list when no files of that kind."
        )
    )
    skipped: list[FolderSkipEntry] = Field(
        default_factory=list,
        description=(
            "Files the walker found but did not classify as ingestable. "
            "Used by the GUI to surface 'we ignored these and why' before "
            "the user presses Import."
        ),
    )
    total_ingestable: int = Field(
        description="Sum of the lengths of files_by_kind — convenience for the GUI.",
    )
    oda: OdaStatus = Field(
        description=(
            "Pre-flight ODA File Converter availability. The GUI uses this "
            "to render an upfront 'install ODA to ingest these N drawings' "
            "callout when files_by_kind.dwg is non-empty and "
            "oda.available is False, instead of letting the user hit the "
            "failure mid-import."
        ),
    )


