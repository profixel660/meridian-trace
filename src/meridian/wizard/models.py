class RuntimeStatusResponse(BaseModel):
    """Operator-facing runtime introspection — alpha-12.

    Triage on a slow / hung / silent backend used to require crawling
    Get-Process + Get-NetTCPConnection + reading log paths the user
    had to know. This endpoint surfaces the same data the backend
    already knows. It is intentionally cheap (no DB queries, no file I/O
    beyond os.getpid) so it stays callable even when the backend is
    under load.

    Why this exists: alpha-11's "documents uploaded then web interface
    broke" triage took 20+ minutes because we had to ask the operator
    to run 4 PowerShell probes to learn things the backend already
    knew (pid, uptime, log paths, last activity). Surface them.
    """

    pid: int = Field(description="OS process ID of this uvicorn worker.")
    started_at: str = Field(
        description="ISO-8601 UTC timestamp of process start.",
    )
    uptime_seconds: float = Field(
        description="Seconds since the process started.",
    )
    version: str = Field(description="Meridian package version (matches /health.version).")
    python_version: str = Field(
        description="CPython version (e.g. '3.12.8') for compatibility triage.",
    )
    platform: str = Field(
        description="OS platform string (e.g. 'win32', 'linux', 'darwin').",
    )
    backend_log_path: str | None = Field(
        default=None,
        description=(
            "Absolute path of the operator-visible backend.log if the "
            "MERIDIAN_BACKEND_LOG env var is set (the installer sets it). "
            "Null when running outside the canonical install layout (dev "
            "tree, gauntlet venv, etc.)."
        ),
    )
    structlog_dir: str | None = Field(
        default=None,
        description=(
            "Absolute path of the directory holding the per-project "
            "JSON-lines structlog files. Null until configure_logging "
            "has run."
        ),
    )
    last_import_job: dict | None = Field(
        default=None,
        description=(
            "Snapshot of the most-recent folder-import job, if any: "
            "{job_id, status, completed, total, last_activity_age_s}. "
            "Null when no job has been kicked this process. Lets a "
            "triage flow answer 'is the worker stuck?' from one HTTP call."
        ),
    )
    auth_disabled: bool = Field(
        description=(
            "Alpha-13: True iff MERIDIAN_AUTH_DISABLED=1 is set and "
            "require_session is short-circuited. The frontend renders a "
            "loud debug-mode banner when this is true so an operator "
            "cannot ship a production build with the bypass on without "
            "noticing. Always present (never null) so the GUI's banner "
            "logic doesn't need an undefined-check."
        ),
    )


class SetupDefaultsResponse(BaseModel):
    """Server-side defaults the frontend pre-fills into form fields.

    Two real, server-resolved paths so the frontend never has to substitute
    placeholder tokens like ``C:\\Users\\<you>\\...`` (the alpha-5 bug
    class — frontend submitted the literal ``<you>`` string and Windows
    path validation rejected the ``<`` and ``>``). Both fields are real
    paths the backend's ``Path()`` constructor can parse without raising.

    * ``projects_dir`` — where the wizard should create new project SQLite
      files (resolves via the same ``_meridian_home()`` chain everything
      else uses: ``MERIDIAN_HOME`` env var, then ``C:\\Meridian`` on
      Windows when present, then ``~/Meridian``, with ``/projects``
      appended).
    * ``home_dir`` — the running OS user's home directory
      (``str(Path.home())``). Alpha-9 added this so the first-documents
      page can build a smart pre-fill for its typed-path input
      (``<home_dir>\\Documents\\<folderName>``) when the browser
      webkitdirectory picker only returns the folder name. Browser
      security hides the absolute path from JS; the Tauri MSI (round 18)
      eliminates this restriction entirely.
    """

    projects_dir: str = Field(
        description=(
            "Absolute path the wizard pre-fills into the first-project "
            "form. Always a real path with no placeholder tokens."
        ),
        min_length=1,
    )
    home_dir: str = Field(
        description=(
            "Running OS user's home directory (str(Path.home())). The "
            "first-documents page uses it to build a smart typed-path "
            "pre-fill of <home_dir>\\Documents\\<folderName> when the "
            "browser folder-picker only exposes the folder name."
        ),
        min_length=1,
    )


